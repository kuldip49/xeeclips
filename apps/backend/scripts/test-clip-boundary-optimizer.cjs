require('reflect-metadata');
const assert=require('node:assert/strict');
const {optimizeClipBoundaries}=require('../dist/modules/processing/clip-boundary-optimizer');
const {ClipBoundaryService}=require('../dist/modules/content-intelligence/clip-boundary.service');
const words='A complete sentence introduces the context for the decision. The explanation continues until the speaker reaches a sustainable conclusion with sufficient detail.'.split(' ').map((text,i)=>({text,start:50+i*.9,end:50+i*.9+.8}));
const last=words.at(-1).end;
const candidate={startTime:51.8,endTime:last-1.4,transcriptText:''};
const repaired=optimizeClipBoundaries(candidate,words);
assert(repaired.valid);assert(repaired.startTime<50);assert(repaired.endTime>=last);
assert(Object.values(repaired.qa).every(Boolean));
const padded=optimizeClipBoundaries({...candidate,startTime:50,endTime:last+5},words);
assert(padded.endTime>=last && padded.endTime<last+5);assert(padded.trailingWasteMs>0);
assert.equal(padded.leadingTrimmedMs,0);
const missing=optimizeClipBoundaries({startTime:5,endTime:40,transcriptText:'Unknown speech'},[]);
assert.equal(missing.startTime,5);assert.equal(missing.endTime,40);assert.equal(missing.evidenceAvailable,false);assert.equal(missing.valid,false);
const invalid=optimizeClipBoundaries({startTime:0,endTime:16,transcriptText:''},[{start:0,end:16,text:'Because the answer is and'}]);
assert.equal(invalid.valid,false);
assert.equal(new ClipBoundaryService().validate(candidate,words).valid,false);
console.log('Shared boundary adapter: bounded expansion, complete sentences, natural tail, honest missing evidence, unfinished-clause rejection and final-range guard passed.');
